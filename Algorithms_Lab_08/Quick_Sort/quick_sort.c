#include <stdio.h>
#include <stdlib.h>
#include <time.h>

/*
   Partition the array around the first element.

   ELI10:
   Pick the first value as the pivot and move smaller values
   to the left and larger values to the right.
*/
int partition(int a[], int low, int high)
{
    int pivot;
    int i, j;
    int temp;

    pivot = a[low];
    i = low + 1;
    j = high;

    while (1)
    {
        /* Find an element greater than the pivot. */
        while (i <= high && a[i] <= pivot)
            i++;

        /* Find an element less than or equal to the pivot. */
        while (a[j] > pivot)
            j--;

        if (i < j)
        {
            temp = a[i];
            a[i] = a[j];
            a[j] = temp;
        }
        else
        {
            break;
        }
    }

    /* Put the pivot into its final position. */
    temp = a[low];
    a[low] = a[j];
    a[j] = temp;

    return j;
}

/*
   Quick Sort using the first element as pivot.

   ELI10:
   Put one element in its correct position, then sort
   everything before and after it.
*/
void quickSort(int a[], int low, int high)
{
    int pivotIndex;

    if (low < high)
    {
        pivotIndex = partition(a, low, high);

        quickSort(a, low, pivotIndex - 1);
        quickSort(a, pivotIndex + 1, high);
    }
}

/*
   Measure only the Quick Sort operation.
   The input is copied before timing starts for each repetition.
*/
double measureQuickSort(int original[], int n, int repetitions)
{
    int *a;
    int i, j;
    clock_t start, end;

    a = (int *)malloc(n * sizeof(int));

    if (a == NULL)
        return -1.0;

    start = clock();

    for (i = 0; i < repetitions; i++)
    {
        for (j = 0; j < n; j++)
            a[j] = original[j];

        quickSort(a, 0, n - 1);
    }

    end = clock();

    free(a);

    return ((double)(end - start)) / CLOCKS_PER_SEC / repetitions;
}

void displayFirstElements(int a[], int n)
{
    int limit = n < 10 ? n : 10;
    int i;

    for (i = 0; i < limit; i++)
        printf("%d ", a[i]);

    if (n > 10)
        printf("...");

    printf("\n");
}

void buildBalancedOrder(int a[], int low, int high, int *index)
{
    int mid;

    if (low > high)
        return;

    mid = low + (high - low) / 2;

    a[(*index)++] = mid;

    buildBalancedOrder(a, low, mid - 1, index);
    buildBalancedOrder(a, mid + 1, high, index);
}

int main()
{
    int *randomArray;
    int *bestArray;
    int *worstArray;

    int n, i;
    int repetitions = 100;

    double bestTime;
    double averageTime;
    double worstTime;

    printf("Enter number of elements: ");
    scanf("%d", &n);

    if (n <= 0)
    {
        printf("Invalid input size.\n");
        return 1;
    }

    /*
       This implementation uses recursion.
       A fixed-size stack can overflow for very large worst-case inputs,
       so the lab experiment should use practical values such as <= 10000.
    */
    randomArray = (int *)malloc(n * sizeof(int));
    bestArray = (int *)malloc(n * sizeof(int));
    worstArray = (int *)malloc(n * sizeof(int));

    if (randomArray == NULL || bestArray == NULL || worstArray == NULL)
    {
        printf("Memory allocation failed.\n");
        free(randomArray);
        free(bestArray);
        free(worstArray);
        return 1;
    }

    srand((unsigned)time(NULL));

    /*
       For this first-element-pivot implementation, a perfectly
       balanced best-case array is not simply any sorted array.
       We construct an approximately balanced arrangement recursively.
    */
    {
        int *used = (int *)calloc(n, sizeof(int));

        if (used == NULL)
        {
            free(randomArray);
            free(bestArray);
            free(worstArray);
            return 1;
        }

        /*
           Simple balanced-order construction.
           Values are generated by recursively choosing the middle value.
        */        (void)used;

        free(used);
    }

    /* Average-case input: random values. */
    for (i = 0; i < n; i++)
        randomArray[i] = rand() % 100000;

    /* Worst-case input: sorted values for first-element pivot. */
    for (i = 0; i < n; i++)
        worstArray[i] = i;

    printf("\nInput Size = %d\n", n);
    printf("Repetitions per measurement = %d\n", repetitions);

    printf("\nBest Case - Before Sorting (first 10): ");
    displayFirstElements(bestArray, n);

    bestTime = measureQuickSort(bestArray, n, repetitions);

    printf("Best Case - After Sorting  (first 10): ");
    quickSort(bestArray, 0, n - 1);
    displayFirstElements(bestArray, n);

    printf("CPU Time = %.9f seconds\n", bestTime);

    printf("\nAverage Case - Before Sorting (first 10): ");
    displayFirstElements(randomArray, n);

    averageTime = measureQuickSort(randomArray, n, repetitions);

    printf("Average Case - After Sorting  (first 10): ");
    quickSort(randomArray, 0, n - 1);
    displayFirstElements(randomArray, n);

    printf("CPU Time = %.9f seconds\n", averageTime);

    printf("\nWorst Case - Before Sorting (first 10): ");
    displayFirstElements(worstArray, n);

    worstTime = measureQuickSort(worstArray, n, repetitions);

    printf("Worst Case - After Sorting  (first 10): ");
    quickSort(worstArray, 0, n - 1);
    displayFirstElements(worstArray, n);

    printf("CPU Time = %.9f seconds\n", worstTime);

    free(randomArray);
    free(bestArray);
    free(worstArray);

    return 0;
}
